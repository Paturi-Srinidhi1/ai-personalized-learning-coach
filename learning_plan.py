
from ai_service import generate_json, AIServiceError

def generate_learning_plan(
    subject,
    goal,
    current_level,
    duration_days,
    daily_minutes,
):
    """Generate and validate a personalized learning plan."""

    if not isinstance(subject, str) or not subject.strip():
        raise AIServiceError("Please enter a valid subject.")

    if not isinstance(goal, str) or not goal.strip():
        raise AIServiceError("Please enter a valid learning goal.")

    if current_level not in ("Beginner", "Intermediate", "Advanced"):
        raise AIServiceError("Please select a valid learning level.")

    if (
        not isinstance(duration_days, int)
        or isinstance(duration_days, bool)
        or not 1 <= duration_days <= 365
    ):
        raise AIServiceError(
            "Learning duration must be between 1 and 365 days."
        )

    if (
        not isinstance(daily_minutes, int)
        or isinstance(daily_minutes, bool)
        or daily_minutes < 1
    ):
        raise AIServiceError(
            "Daily study time must be at least one minute."
        )

    prompt = f"""
Create a personalized learning plan for a learner.

Subject: {subject.strip()}
Learning goal: {goal.strip()}
Current level: {current_level}
Duration: {duration_days} days
Available study time: {daily_minutes} minutes per day

Return a valid JSON object with this exact structure:
{{
    "title": "A suitable learning plan title",
    "subject": "{subject.strip()}",
    "overview": "A short explanation of the plan",
    "weekly_plan": [
        {{
            "week": 1,
            "topics": ["Topic 1", "Topic 2"],
            "activities": ["Activity 1", "Activity 2"],
            "milestone": "What the learner should achieve"
        }}
    ],
    "daily_routine": [
        {{
            "activity": "Study concepts",
            "minutes": 30
        }}
    ],
    "success_tips": [
        "A practical learning tip"
    ]
}}

Requirements:
- Adjust the plan to fit the requested duration.
- Include enough weeks to cover the full duration.
- Begin with foundational concepts for beginners.
- Match topics to the subject and learning goal.
- Include practical exercises, revision, and progress checks.
- Keep the total daily routine within {daily_minutes} minutes.
- Use clear, achievable milestones.
- Include useful, non-empty topics, activities, and success tips.
- Return valid JSON only, without Markdown fences.
"""

    try:
        result = generate_json(prompt)

    except AIServiceError:
    # Clearly labelled fallback when Gemini is unavailable.
     number_of_weeks = (duration_days + 6) // 7

    weekly_plan = []

    for week_number in range(1, number_of_weeks + 1):
        weekly_plan.append({
            "week": week_number,
            "topics": [
                f"{subject}: core concepts",
                f"{subject}: practical exercises and revision",
            ],
            "activities": [
                "Study the key concepts and take notes.",
                "Practise with examples related to your goal.",
                "Review difficult topics and check your understanding.",
            ],
            "milestone": (
                f"Review the material from week {week_number} "
                "and complete a self-assessment."
            ),
        })

    first_minutes = daily_minutes // 2
    second_minutes = daily_minutes - first_minutes

    result = {
        "title": f"{duration_days}-Day {subject} Learning Plan",
        "subject": subject.strip(),
        "overview": (
            f"This is a locally generated backup plan for your goal: "
            f"{goal}. Gemini was unavailable, so this plan was not "
            "generated by AI."
        ),
        "weekly_plan": weekly_plan,
        "daily_routine": [
            {
                "activity": "Learn concepts and make notes",
                "minutes": first_minutes,
            },
            {
                "activity": "Practise and revise",
                "minutes": second_minutes,
            },
        ],
        "success_tips": [
            "Study consistently each day.",
            "Practise examples related to your goal.",
            "Review difficult topics regularly.",
        ],
    }

    if not isinstance(result, dict):
        raise AIServiceError(
            "The AI returned an invalid learning plan."
        )

    required_keys = (
        "title",
        "subject",
        "overview",
        "weekly_plan",
        "daily_routine",
        "success_tips",
    )

    for key in required_keys:
        if key not in result:
            raise AIServiceError(
                f"The learning plan is missing the '{key}' section."
            )

    for key in ("title", "subject", "overview"):
        if (
            not isinstance(result[key], str)
            or not result[key].strip()
        ):
            raise AIServiceError(
                f"The learning plan has an empty or invalid '{key}' field."
            )

    if not isinstance(result["weekly_plan"], list) or not result["weekly_plan"]:
        raise AIServiceError(
            "The learning plan must contain at least one week."
        )

    if not isinstance(result["daily_routine"], list) or not result["daily_routine"]:
        raise AIServiceError(
            "The daily routine must contain at least one activity."
        )

    if not isinstance(result["success_tips"], list) or not result["success_tips"]:
        raise AIServiceError(
            "The learning plan must contain at least one success tip."
        )

    for index, week in enumerate(result["weekly_plan"], start=1):
        if not isinstance(week, dict):
            raise AIServiceError(
                f"Week {index} has an invalid format."
            )

        for key in ("week", "topics", "activities", "milestone"):
            if key not in week:
                raise AIServiceError(
                    f"Week {index} is missing the '{key}' field."
                )

        if not isinstance(week["topics"], list) or not week["topics"]:
            raise AIServiceError(
                f"Week {index} must contain at least one topic."
            )

        if not isinstance(week["activities"], list) or not week["activities"]:
            raise AIServiceError(
                f"Week {index} must contain at least one activity."
            )

        if (
            not isinstance(week["milestone"], str)
            or not week["milestone"].strip()
        ):
            raise AIServiceError(
                f"Week {index} must have a milestone."
            )

    total_daily_minutes = 0

    for index, activity in enumerate(
        result["daily_routine"],
        start=1,
    ):
        if not isinstance(activity, dict):
            raise AIServiceError(
                f"Daily routine activity {index} has an invalid format."
            )

        name = activity.get("activity")
        minutes = activity.get("minutes")

        if not isinstance(name, str) or not name.strip():
            raise AIServiceError(
                f"Daily routine activity {index} has no name."
            )

        if (
            not isinstance(minutes, int)
            or isinstance(minutes, bool)
            or minutes < 0
        ):
            raise AIServiceError(
                f"Daily routine activity {index} has invalid minutes."
            )

        total_daily_minutes += minutes

    if total_daily_minutes > daily_minutes:
        raise AIServiceError(
            "The generated daily routine exceeds your available "
            "study time. Please generate the plan again."
        )

    for index, tip in enumerate(result["success_tips"], start=1):
        if not isinstance(tip, str) or not tip.strip():
            raise AIServiceError(
                f"Success tip {index} is empty or invalid."
            )

    return result
